def _save_and_url(
    pil_image: Image.Image,
    prefix: str,
    ext: str = "png",
) -> str:
    """
    Save a PIL image into outputs/ and return the frontend URL.
    """

    filename = (
        f"{prefix}_"
        f"{uuid.uuid4().hex[:8]}."
        f"{ext}"
    )

    path = os.path.join(
        OUTPUTS_DIR,
        filename,
    )

    pil_image.convert(
        "RGB"
    ).save(
        path,
        format="PNG",
    )

    return (
        f"/files/{filename}"
    )


