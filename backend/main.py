# ===========================================================================
# JOB TRACKER
# ===========================================================================

_jobs = {}

_jobs_lock = threading.Lock()


def _make_job():
    """
    Create a new generation job.

    Progress is represented as 0-100 so the frontend does not need to know
    the internal DDPM/ESRGAN stages.
    """

    job_id = uuid.uuid4().hex

    with _jobs_lock:

        _jobs[job_id] = {
            "status": "running",
            "step": 0,
            "total": 100,
            "stage": "starting",
            "result": None,
            "error": None,
        }

    return job_id


def _update_job(
    job_id,
    step=None,
    stage=None,
):
    """
    Update generation progress.
    """

    with _jobs_lock:

        job = _jobs.get(job_id)

        if job is None:
            return

        if step is not None:

            job["step"] = max(
                0,
                min(
                    100,
                    int(step),
                ),
            )

        if stage is not None:

            job["stage"] = stage


def _finish_job(
    job_id,
    result=None,
    error=None,
):
    """
    Finish a generation job.
    """

    with _jobs_lock:

        job = _jobs.get(job_id)

        if job is None:
            return

        if error:

            job["status"] = "error"
            job["error"] = error
            job["stage"] = "error"

        else:

            job["status"] = "done"
            job["step"] = 100
            job["stage"] = "complete"
            job["result"] = result
            job["error"] = None


@app.get(
    "/api/generation-progress/{job_id}"
)
def generation_progress(
    job_id: str,
):
    """
    Return the current state of a generation job.
    """

    with _jobs_lock:

        job = _jobs.get(job_id)

    if job is None:

        raise HTTPException(
            status_code=404,
            detail="Unknown job_id",
        )

    return job


# ===========================================================================
# FILE SAVING
