class VideoRequest(
    BaseModel
):

    image_urls: list[str]


@app.post(
    "/api/generate-video"
)
def generate_video(
    req: VideoRequest,
):

    images = []

    for url in req.image_urls:

        filename = (
            url.split(
                "/files/"
            )[-1]
        )

        path = os.path.join(
            OUTPUTS_DIR,
            filename,
        )

        if not os.path.exists(path):

            raise HTTPException(
                status_code=404,
                detail=(
                    f"Image not found: {url}"
                ),
            )

        images.append(
            Image.open(
                path
            ).convert(
                "RGB"
            )
        )

    video_filename = (
        f"video_"
        f"{uuid.uuid4().hex[:8]}"
        f".mp4"
    )

    video_path = os.path.join(
        OUTPUTS_DIR,
        video_filename,
    )

    video_generation.generate_video(
        images,
        mode="slideshow",
        output_path=video_path,
    )

    return {
        "video_url": (
            f"/files/{video_filename}"
        )
    }


