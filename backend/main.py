class TextToImageRequest(
    BaseModel
):

    prompt: str
    use_background: bool = False


@app.post(
    "/api/generate-image-from-text/start"
)
def generate_image_from_text_start(
    req: TextToImageRequest,
):

    job_id = _make_job()

    def run():

        try:

            # --------------------------------------------------------------
            # DDPM PROGRESS
            # --------------------------------------------------------------

            def progress_cb(
                step,
                total,
            ):

                if total:

                    ddpm_progress = (
                        float(step)
                        / float(total)
                    )

                    overall = int(
                        ddpm_progress * 80
                    )

                else:

                    overall = 1

                _update_job(
                    job_id,
                    overall,
                    "generating with RANANO DDPM",
                )

            # --------------------------------------------------------------
            # RANANO DDPM
            # --------------------------------------------------------------

            img, matched_classes, note = (
                image_generation.generate_image_from_prompt(
                    req.prompt,
                    image_generation.CHECKPOINT_PATH,
                    req.use_background,
                    progress_callback=progress_cb,
                )
            )

            print(
                "[RANANO] DDPM generation complete: "
                f"{img.size[0]}x{img.size[1]}",
                flush=True,
            )

            # --------------------------------------------------------------
            # BACKGROUND / COMPOSITING
            # --------------------------------------------------------------

            _update_job(
                job_id,
                84,
                "processing background and composition",
            )

            # The background work, if requested, has already been performed
            # inside generate_image_from_prompt().
            #
            # We keep this separate progress stage so the frontend does not
            # display 100% while post-processing is still running.

            # --------------------------------------------------------------
            # ESRGAN
            # --------------------------------------------------------------

            _update_job(
                job_id,
                88,
                "enhancing with ESRGAN",
            )

            img = super_resolution.enhance_generated_image(
                img
            )

            print(
                "[RANANO] ESRGAN enhancement complete: "
                f"{img.size[0]}x{img.size[1]}",
                flush=True,
            )

            # --------------------------------------------------------------
            # SAVE
            # --------------------------------------------------------------

            _update_job(
                job_id,
                97,
                "saving final image",
            )

            url = _save_and_url(
                img,
                "generated",
            )

            print(
                f"[RANANO] Generation complete: {url}",
                flush=True,
            )

            _finish_job(
                job_id,
                result={
                    "image_url": url,
                    "matched_classes": (
                        matched_classes
                    ),
                    "note": note,
                    "generation_size": [
                        96,
                        96,
                    ],
                    "final_size": list(
                        img.size
                    ),
                    "enhancement": (
                        "TensorFlow Hub ESRGAN x4"
                    ),
                    "super_resolution_model": (
                        "ESRGAN x4"
                    ),
                },
            )

        except Exception as exc:

            print(
                "[RANANO] Text generation failed:",
                repr(exc),
                flush=True,
            )

            _finish_job(
                job_id,
                error=str(exc),
            )

    _generation_executor.submit(
        run
    )

    return {
        "job_id": job_id
    }


