# IMAGE ENHANCEMENT
# ===========================================================================

@app.post(
    "/api/enhance-image"
)
async def enhance_image(
    file: UploadFile = File(...),
    mode: str = Form("fast"),
):

    try:

        contents = await file.read()

        safe_filename = (
            f"{uuid.uuid4().hex[:8]}_"
            f"{file.filename}"
        )

        upload_path = os.path.join(
            UPLOADS_DIR,
            safe_filename,
        )

        with open(
            upload_path,
            "wb",
        ) as f:

            f.write(contents)

        image = Image.open(
            upload_path
        ).convert(
            "RGB"
        )

        # --------------------------------------------------------------
        # Enhancement modes:
        #
        # fast
        #     Classical OpenCV cleanup.
        #
        # quality / esrgan
        #     TensorFlow Hub ESRGAN x4.
        # --------------------------------------------------------------

        if mode.lower() in {
            "quality",
            "esrgan",
            "super_resolution",
        }:

            enhanced = (
                super_resolution.enhance_uploaded_image(
                    image
                )
            )

        else:

            enhanced = (
                image_enhancement.enhance(
                    image,
                    mode="fast",
                )
            )

        url = _save_and_url(
            enhanced,
            "enhanced",
        )

        return {
            "image_url": url,
            "mode": mode,
            "enhancement": (
                "TensorFlow Hub ESRGAN x4"
                if mode.lower()
                in {
                    "quality",
                    "esrgan",
                    "super_resolution",
                }
                else "Fast OpenCV enhancement"
            ),
        }

    except Exception as exc:

        print(
            "[RANANO] Image enhancement failed:",
            repr(exc),
            flush=True,
        )

        raise HTTPException(
            status_code=500,
            detail=str(exc),
        )


