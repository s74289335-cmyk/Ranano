# RANDOM IMAGE GENERATION
# ===========================================================================

@app.post(
    "/api/generate-image/start"
)
def generate_image_start():

    job_id = _make_job()

    def run():

        try:

            # --------------------------------------------------------------
            # DDPM: 0 -> 80
            # --------------------------------------------------------------

            _update_job(
                job_id,
                1,
                "generating with RANANO DDPM",
            )

            def progress_cb(
                step,
                total,
            ):

                if total:

                    ddpm_progress = (
                        float(step)
                        / float(total)
                    )

                    overall = int(
                        ddpm_progress * 80
                    )

                else:

                    overall = 1

                _update_job(
                    job_id,
                    overall,
                    "generating with RANANO DDPM",
                )

            img = image_generation.generate_image(
                progress_callback=progress_cb
            )

            print(
                "[RANANO] DDPM generation complete: "
                f"{img.size[0]}x{img.size[1]}",
                flush=True,
            )

            # --------------------------------------------------------------
            # ESRGAN: 80 -> 97
            # --------------------------------------------------------------

            _update_job(
                job_id,
                82,
                "enhancing with ESRGAN",
            )

            img = super_resolution.enhance_generated_image(
                img
            )

            _update_job(
                job_id,
                97,
                "saving final image",
            )

            print(
                "[RANANO] ESRGAN enhancement complete: "
                f"{img.size[0]}x{img.size[1]}",
                flush=True,
            )

            # --------------------------------------------------------------
            # SAVE: 97 -> 100
            # --------------------------------------------------------------

            url = _save_and_url(
                img,
                "generated",
            )

            print(
                f"[RANANO] Generation complete: {url}",
                flush=True,
            )

            _finish_job(
                job_id,
                result={
                    "image_url": url,
                    "generation_size": [
                        96,
                        96,
                    ],
                    "final_size": list(
                        img.size
                    ),
                    "enhancement": (
                        "TensorFlow Hub ESRGAN x4"
                    ),
                    "super_resolution_model": (
                        "ESRGAN x4"
                    ),
                },
            )

        except Exception as exc:

            print(
                "[RANANO] Random generation failed:",
                repr(exc),
                flush=True,
            )

            _finish_job(
                job_id,
                error=str(exc),
            )

    _generation_executor.submit(
        run
    )

    return {
        "job_id": job_id
    }


