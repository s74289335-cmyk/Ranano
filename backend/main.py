@app.post(
    "/api/label-photo"
)
async def label_photo_endpoint(
    file: UploadFile = File(...),
    effect: str = Form("fade"),
):

    try:

        contents = await file.read()

        safe_filename = (
            f"{uuid.uuid4().hex[:8]}_"
            f"{file.filename}"
        )

        upload_path = os.path.join(
            UPLOADS_DIR,
            safe_filename,
        )

        with open(
            upload_path,
            "wb",
        ) as f:

            f.write(contents)

        image = Image.open(
            upload_path
        ).convert(
            "RGB"
        )

        gif_filename = (
            f"label_"
            f"{uuid.uuid4().hex[:8]}"
            f".gif"
        )

        gif_path = os.path.join(
            OUTPUTS_DIR,
            gif_filename,
        )

        label, confidence, saved_path = (
            photo_label.label_and_animate(
                image,
                output_path=gif_path,
                effect=effect,
            )
        )

        return {
            "label": label,
            "confidence": confidence,
            "gif_url": (
                f"/files/{gif_filename}"
            ),
        }

    except FileNotFoundError as exc:

        raise HTTPException(
            status_code=503,
            detail=str(exc),
        )


